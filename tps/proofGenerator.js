'use strict';

/**
 * TPS-side witness construction and proof generation (Section V-D, V-E).
 *
 * The TPS combines:
 *   - provider-controlled policy material  (penc, randomizer, paramsCommitment, …)
 *   - requester-submitted authorization evidence  (attributes a, predicate evidence p, ω)
 *
 * and constructs the private witness  w = (penc, a, p, r, ω)
 * before calling snarkjs to generate the Groth16 proof.
 *
 * Circuit parameters (must match policy_privacy_main_instance.circom):
 *   N=13 attributes, M=11 fixed predicates, DEPTH=64, K=5
 */

const path = require('path');
const fs = require('fs');
const {
    initPoseidon,
    calculateParamsCommitment,
    calculateContextHash,
    normalizePredicateTypesInPlace: _normalizePredicateTypesInPlace,
    generateProof: _rawGenerateProof
} = require('../lib/prover');


// Circuit build artefacts – generated by `npm run build:circuit:full`.
// CI may point at an isolated, disposable setup so it never overwrites the
// canonical release-candidate artefacts.
const BUILD_DIR = process.env.PROTOCOL_CIRCUITS_DIR
    ? path.resolve(process.env.PROTOCOL_CIRCUITS_DIR)
    : path.resolve(__dirname, '../build/circuits');
const WASM_PATH = path.join(BUILD_DIR, 'policy_privacy_main_instance_js', 'policy_privacy_main_instance.wasm');
const ZKEY_PATH = path.join(BUILD_DIR, 'policy_privacy_main_final.zkey');
const VKEY_PATH = path.join(BUILD_DIR, 'policy_privacy_main_vk.json');

// Must match the concrete circuit instantiation in
// circuits/policy_privacy_main_instance.circom. PROTOCOL_CIRCUIT_DEPTH and
// PROTOCOL_MERKLE_LEVELS let the offline scalability sweep prove against a
// build compiled at another capacity; production and capture runs leave both
// unset and therefore retain the frozen RC1 dimensions.
const CIRCUIT = {
    N: 13,
    M: 11,
    DEPTH: Number(process.env.PROTOCOL_CIRCUIT_DEPTH || 64),
    K: 5,
    MERKLE_LEVELS: Number(process.env.PROTOCOL_MERKLE_LEVELS || 8)
};

/**
 * Build the full circuit witness from policy material + requester evidence.
 *
 * @param {object} policyMaterial  Provisioned by the provider via TPS.provision.
 *   {
 *     penc          : number[]   – fixed-length RPN token array (length DEPTH)
 *     randomizer    : string     – BigInt string
 *     paramsCommitment: string   – pre-computed params commitment
 *     merkleRoots   : string[]
 *     credPublicKeys: string[]
 *     rangeMin      : string[]
 *     rangeMax      : string[]
 *     ontologyPolicyIds: string[]
 *     ontologyEpochs: string[]
 *     numOperations : number
 *   }
 * @param {object} evidence  Submitted by the requester.
 *   {
 *     attributes    : number[]   – Boolean attribute vector a ∈ {0,1}^N
 *     purposeCode   : bigint     – private declared request purpose
 *     merkleLeaves  : string[]   (optional)
 *     merklePathElements: string[][] (optional)
 *     merklePathIndices : number[][] (optional)
 *     credSignatures: string[]   (optional)  EdDSA scalar S
 *     credSigR8x    : string[]   (optional)  EdDSA point R8.x
 *     credSigR8y    : string[]   (optional)  EdDSA point R8.y
 *     credIssuerAx  : string[]   (optional)  issuer key point x
 *     credIssuerAy  : string[]   (optional)  issuer key point y
 *     rangeValues   : number[]   (optional)
 *     ontologyCodes : number[]   (optional)
 *   }
 * @param {object} publicInputs
 *   {
 *     policyCommitment : string  – h = Com(penc; r)
 *   }
 * @returns {object}  snarkjs circuit input ready for fullProve
 */
function buildWitness(policyMaterial, evidence, publicInputs) {
    const { DEPTH, N, M, MERKLE_LEVELS } = CIRCUIT;

    // Validate the authorization context before any String() coercion below.
    // String(undefined) yields the string "undefined", which survives the
    // emptiness checks in calculateContextHash and only fails much later, at
    // BigInt("undefined"), with an error that points away from the real cause:
    // a caller that omitted the context entirely.
    for (const name of ['idReq', 'idRes', 'nonce']) {
        const value = publicInputs ? publicInputs[name] : undefined;
        if (value === undefined || value === null || value === '') {
            throw new Error(
                `buildWitness requires publicInputs.${name}: the authorization ` +
                `context (requester, resource, session) is bound into the proof ` +
                `statement and must be supplied by the caller.`
            );
        }
    }

    const penc = Array.isArray(policyMaterial.penc)
        ? policyMaterial.penc.slice()
        : [];

    // Pad / truncate policy to fixed DEPTH
    const policy = penc.length >= DEPTH
        ? penc.slice(0, DEPTH)
        : [...penc, ...Array(DEPTH - penc.length).fill(0)];

    // Pad / truncate attribute vector to N
    const rawAttrs = Array.isArray(evidence.attributes) ? evidence.attributes : [];
    const requesterAttrs = rawAttrs.length >= N
        ? rawAttrs.slice(0, N)
        : [...rawAttrs, ...Array(N - rawAttrs.length).fill(0)];

    const zero = (n) => Array(n).fill(0);
    const zeroStr = (n) => Array(n).fill('0');
    const zeroMat = (rows, cols) => Array.from({ length: rows }, () => Array(cols).fill('0'));
    const zeroMatNum = (rows, cols) => Array.from({ length: rows }, () => Array(cols).fill(0));

    const exactPolicyArray = (value, name) => {
        if (!Array.isArray(value) || value.length !== M) {
            throw new Error(`policyMaterial.${name} must contain exactly ${M} entries`);
        }
        return value.slice();
    };

    // Predicate semantics are policy parameters, never requester evidence.
    // Allowing evidence to select a verifier would permit type substitution.
    const predicateTypes = exactPolicyArray(policyMaterial.predicateTypes, 'predicateTypes');
    const predicateSchemaTags = exactPolicyArray(policyMaterial.predicateSchemaTags, 'predicateSchemaTags');
    const scopeKinds = Array.isArray(policyMaterial.scopeKinds)
        ? exactPolicyArray(policyMaterial.scopeKinds, 'scopeKinds') : zero(M);
    const approvedScopeIds = Array.isArray(policyMaterial.approvedScopeIds)
        ? exactPolicyArray(policyMaterial.approvedScopeIds, 'approvedScopeIds') : zeroStr(M);
    const merkleLeaves = (evidence.merkleLeaves || zeroStr(M)).slice(0, M);
    const merklePathElements = (evidence.merklePathElements || zeroMat(M, MERKLE_LEVELS)).slice(0, M);
    const merklePathIndices = (evidence.merklePathIndices || zeroMatNum(M, MERKLE_LEVELS)).slice(0, M);
    const credSignatures = (evidence.credSignatures || zeroStr(M)).slice(0, M);
    // EdDSA signature points and issuer key point. The circuit checks these
    // only for slots whose predicateType selects the credential predicate.
    const credSigR8x = (evidence.credSigR8x || zeroStr(M)).slice(0, M);
    const credSigR8y = (evidence.credSigR8y || zeroStr(M)).slice(0, M);
    const credIssuerAx = (evidence.credIssuerAx || zeroStr(M)).slice(0, M);
    const credIssuerAy = (evidence.credIssuerAy || zeroStr(M)).slice(0, M);
    const rangeValues = (evidence.rangeValues || zero(M)).slice(0, M);
    const ontologyCodes = (evidence.ontologyCodes || zero(M)).slice(0, M);
    const purposeCode = evidence.purposeCode ?? 0;
    const credValidFromEpochs = (evidence.credValidFromEpochs || zeroStr(M)).slice(0, M);
    const credValidUntilEpochs = (evidence.credValidUntilEpochs || zeroStr(M)).slice(0, M);
    const credentialIds = (evidence.credentialIds || zeroStr(M)).slice(0, M);
    const holderSecret = evidence.holderSecret ?? 0;
    const duoProfileClaims = evidence.duoProfileClaims ?? 0;
    if (!Number.isInteger(Number(duoProfileClaims)) || Number(duoProfileClaims) < 0 || Number(duoProfileClaims) > 127) {
        throw new Error('evidence.duoProfileClaims must be a 7-bit integer');
    }
    if (!Number.isInteger(policyMaterial.numOperations) || policyMaterial.numOperations <= 0 || policyMaterial.numOperations > DEPTH) {
        throw new Error(`policyMaterial.numOperations must be an integer in [1, ${DEPTH}]`);
    }

    // HTTP callers pass the chain-hour bucket explicitly. Keep the direct TPS
    // library ergonomic by deriving the same bucket when it is omitted.
    const requestEpoch = publicInputs.requestEpoch === undefined || publicInputs.requestEpoch === null
        ? Math.floor(Date.now() / 3_600_000)
        : publicInputs.requestEpoch;

    const input = {
        // Private witness
        policy,
        requesterAttrs,
        predicateTypes,
        predicateSchemaTags,
        scopeKinds,
        approvedScopeIds,
        merkleLeaves,
        merklePathElements,
        merklePathIndices,
        credSignatures,
        credSigR8x,
        credSigR8y,
        credIssuerAx,
        credIssuerAy,
        rangeValues,
        ontologyCodes,
        purposeCode: String(purposeCode),
        duoProfileClaims: String(duoProfileClaims),
        credValidFromEpochs,
        credValidUntilEpochs,
        credentialIds,
        holderSecret: String(holderSecret),
        randomizer: policyMaterial.randomizer.toString(),
        numOperations: policyMaterial.numOperations,

        // Private circuit inputs; the bound ACM call also publishes these
        // values as transaction calldata so it can recompute the digest.
        idReq: String(publicInputs.idReq),
        idRes: String(publicInputs.idRes),
        nonce: String(publicInputs.nonce),

        // Public inputs
        policyCommitment: publicInputs.policyCommitment,
        paramsCommitment: policyMaterial.paramsCommitment,
        merkleRoots: exactPolicyArray(policyMaterial.merkleRoots, 'merkleRoots'),
        credPublicKeys: exactPolicyArray(policyMaterial.credPublicKeys, 'credPublicKeys'),
        rangeMin: exactPolicyArray(policyMaterial.rangeMin, 'rangeMin'),
        rangeMax: exactPolicyArray(policyMaterial.rangeMax, 'rangeMax'),
        ontologyPolicyIds: exactPolicyArray(policyMaterial.ontologyPolicyIds, 'ontologyPolicyIds'),
        ontologyEpochs: exactPolicyArray(policyMaterial.ontologyEpochs, 'ontologyEpochs'),
        policyValidFromEpoch: String(policyMaterial.policyValidFromEpoch),
        policyValidUntilEpoch: String(policyMaterial.policyValidUntilEpoch),
        moratoriumUntilEpoch: String(policyMaterial.moratoriumUntilEpoch ?? 0),
        timeLimitEpochs: String(policyMaterial.timeLimitEpochs ?? 0),
        requestEpoch: String(requestEpoch)
    };

    return input;
}

/**
 * TPS proof generation entry point (paper Section V-E, Stage 4).
 *
 * @param {object} policyMaterial   from tps/store.getPolicyMaterial(policyId)
 * @param {object} evidence         requester-submitted authorization evidence
 * @param {object} publicInputs     { policyCommitment, idReq, idRes, nonce }
 * @returns {Promise<{pA, pB, pC, pubSignals}>}
 */
async function generateProof(policyMaterial, evidence, publicInputs) {
    if (!fs.existsSync(WASM_PATH)) {
        throw new Error(
            `Circuit WASM not found at ${WASM_PATH}. ` +
            `Run "npm run build:circuit:full" first.`
        );
    }
    if (!fs.existsSync(ZKEY_PATH)) {
        throw new Error(
            `ZKey not found at ${ZKEY_PATH}. ` +
            `Run "npm run build:circuit:full" first.`
        );
    }

    const witness = buildWitness(policyMaterial, evidence, publicInputs);

    // Always recompute paramsCommitment from the actual parameter arrays so it
    // matches what the circuit recomputes internally from those same arrays.
    witness.paramsCommitment = await calculateParamsCommitment({
        predicateTypes: witness.predicateTypes,
        predicateSchemaTags: witness.predicateSchemaTags,
        merkleRoots: witness.merkleRoots,
        credPublicKeys: witness.credPublicKeys,
        rangeMin: witness.rangeMin,
        rangeMax: witness.rangeMax,
        ontologyPolicyIds: witness.ontologyPolicyIds,
        ontologyEpochs: witness.ontologyEpochs,
        scopeKinds: witness.scopeKinds,
        approvedScopeIds: witness.approvedScopeIds,
        policyValidFromEpoch: witness.policyValidFromEpoch,
        policyValidUntilEpoch: witness.policyValidUntilEpoch,
        moratoriumUntilEpoch: witness.moratoriumUntilEpoch,
        timeLimitEpochs: witness.timeLimitEpochs
    });

    if (policyMaterial.paramsCommitment && String(policyMaterial.paramsCommitment) !== witness.paramsCommitment) {
        throw new Error('Provisioned paramsCommitment does not match DUO V3 policy parameters');
    }

    // Bind the authorization context into the statement: the digest is a public
    // signal the ACM recomputes from the transaction parameters, so a proof
    // issued for one (requester, resource, session) triple cannot be replayed
    // under another.
    witness.contextHash = await calculateContextHash(
        witness.idReq,
        witness.idRes,
        witness.nonce
    );

    // Returns { pA, pB, pC, pubSignals, timings } — timings passed through to
    // the prove response so per-execution proof costs can be recorded.
    return _rawGenerateProof(witness, {
        wasmPath: WASM_PATH,
        zkeyPath: ZKEY_PATH,
        vkeyPath: VKEY_PATH
    });
}

module.exports = { generateProof, buildWitness, WASM_PATH, ZKEY_PATH, VKEY_PATH };
